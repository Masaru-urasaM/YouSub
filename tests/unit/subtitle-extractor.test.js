import { jest, describe, test, expect, beforeEach, afterEach } from '@jest/globals';

// chrome mock auto-loads via jest.config.js setupFilesAfterEach.
// SubtitleExtractor imports devLog/devWarn from constants.js (IS_PRODUCTION=false),
// which forward to console — no module mocking required.
import { SubtitleExtractor, deriveSourceLang } from '../../src/content/subtitle-extractor.js';

/**
 * SubtitleExtractor.extract() works in two parts:
 *   1. It injects a <script> (src = chrome.runtime.getURL('src/content/main-world-extractor.js'))
 *      into document.head to run page-side caption scraping.
 *   2. It registers a window 'message' listener and, when it receives a message
 *      whose data.type === 'YOUSUB_CAPTION_TRACKS' from the same window, it fires
 *      the callback once with (tracks, parsedEntries, error, sourceLang) and removes
 *      itself. sourceLang is derived from tracks via deriveSourceLang().
 *
 * jsdom cannot execute the injected script or run a real YouTube page, so we test
 * the injection mechanics, the message filtering/routing, and the one-shot cleanup
 * by dispatching synthetic window 'message' events. The script's onload/onerror
 * handlers depend on a real network fetch and are documented as untestable here.
 */
function postCaptionMessage({ tracks = null, parsedEntries = null, error = null } = {}) {
  const event = new Event('message');
  // The handler checks event.source === window, so define it explicitly.
  Object.defineProperty(event, 'source', { value: window, configurable: true });
  Object.defineProperty(event, 'data', {
    value: { type: 'YOUSUB_CAPTION_TRACKS', tracks, parsedEntries, error },
    configurable: true,
  });
  window.dispatchEvent(event);
}

function postRawMessage(data, source = window) {
  const event = new Event('message');
  Object.defineProperty(event, 'source', { value: source, configurable: true });
  Object.defineProperty(event, 'data', { value: data, configurable: true });
  window.dispatchEvent(event);
}

describe('SubtitleExtractor', () => {
  beforeEach(() => {
    document.head.innerHTML = '';
    document.body.innerHTML = '';
    SubtitleExtractor.destroy();
    jest.clearAllMocks();
  });

  afterEach(() => {
    SubtitleExtractor.destroy();
  });

  describe('Main-world postMessage dispatch', () => {
    test('dispatches YOUSUB_EXTRACT_CAPTIONS via window.postMessage without DOM <script> injection', () => {
      const postSpy = jest.spyOn(window, 'postMessage').mockImplementation(() => {});
      SubtitleExtractor.extract(jest.fn());

      expect(document.head.querySelector('script')).toBeNull();
      expect(chrome.runtime.getURL).not.toHaveBeenCalled();
      expect(postSpy).toHaveBeenCalledWith(
        expect.objectContaining({
          type: 'YOUSUB_EXTRACT_CAPTIONS',
          requestId: expect.any(String),
        }),
        '*'
      );
      postSpy.mockRestore();
    });

    test('registers a window message listener that survives until a caption message', () => {
      const callback = jest.fn();
      SubtitleExtractor.extract(callback);

      // No message yet -> callback not fired.
      expect(callback).not.toHaveBeenCalled();
    });

    test('ignores stale YOUSUB_CAPTION_TRACKS responses carrying a mismatched requestId', () => {
      const postSpy = jest.spyOn(window, 'postMessage').mockImplementation(() => {});
      const callback = jest.fn();
      SubtitleExtractor.extract(callback);

      const dispatchedReqId = postSpy.mock.calls.find(
        (c) => c[0] && c[0].type === 'YOUSUB_EXTRACT_CAPTIONS'
      )[0].requestId;
      postSpy.mockRestore();

      postRawMessage({
        type: 'YOUSUB_CAPTION_TRACKS',
        requestId: 'stale_req_id',
        tracks: [],
        parsedEntries: [{ startMs: 0, endMs: 1, text: 'stale' }],
      });
      expect(callback).not.toHaveBeenCalled();

      postRawMessage({
        type: 'YOUSUB_CAPTION_TRACKS',
        requestId: dispatchedReqId,
        tracks: [],
        parsedEntries: [{ startMs: 0, endMs: 1, text: 'fresh' }],
        error: null,
      });
      expect(callback).toHaveBeenCalledTimes(1);
      expect(callback).toHaveBeenCalledWith(
        [],
        [{ startMs: 0, endMs: 1, text: 'fresh' }],
        null,
        'auto'
      );
    });
  });

  describe('Message routing', () => {
    test('fires the callback with parsed entries when a caption message arrives', () => {
      const callback = jest.fn();
      SubtitleExtractor.extract(callback);

      const tracks = [{ languageCode: 'en', languageName: 'English', isAutoGenerated: true }];
      const parsedEntries = [{ startMs: 0, endMs: 1000, text: 'Hello' }];
      postCaptionMessage({ tracks, parsedEntries });

      expect(callback).toHaveBeenCalledTimes(1);
      // Single track with a known languageCode → concrete source language.
      expect(callback).toHaveBeenCalledWith(tracks, parsedEntries, null, 'en');
    });

    test('fires the callback with tracks-only (no parsed entries)', () => {
      const callback = jest.fn();
      SubtitleExtractor.extract(callback);

      const tracks = [
        { languageCode: 'en', languageName: 'English', isAutoGenerated: false },
        { languageCode: 'ja', languageName: 'Japanese', isAutoGenerated: true },
      ];
      postCaptionMessage({ tracks, parsedEntries: [] });

      expect(callback).toHaveBeenCalledTimes(1);
      // Multiple tracks → ambiguous → 'auto'.
      expect(callback).toHaveBeenCalledWith(tracks, [], null, 'auto');
    });

    test('fires the callback with an error string when the message carries an error', () => {
      const callback = jest.fn();
      SubtitleExtractor.extract(callback);

      postCaptionMessage({ error: 'No captions found' });

      expect(callback).toHaveBeenCalledTimes(1);
      expect(callback).toHaveBeenCalledWith(null, null, 'No captions found', 'auto');
    });

    test('handles the empty case (no tracks, no entries, no error)', () => {
      const callback = jest.fn();
      SubtitleExtractor.extract(callback);

      postCaptionMessage({});

      expect(callback).toHaveBeenCalledTimes(1);
      expect(callback).toHaveBeenCalledWith(null, null, null, 'auto');
    });
  });

  describe('Message filtering', () => {
    test('ignores messages from a different source (event.source !== window)', () => {
      const callback = jest.fn();
      SubtitleExtractor.extract(callback);

      const fakeSource = {};
      postRawMessage({ type: 'YOUSUB_CAPTION_TRACKS', tracks: [], parsedEntries: [] }, fakeSource);

      expect(callback).not.toHaveBeenCalled();
    });

    test('ignores messages with a non-matching type', () => {
      const callback = jest.fn();
      SubtitleExtractor.extract(callback);

      postRawMessage({ type: 'SOME_OTHER_MESSAGE', payload: 1 });

      expect(callback).not.toHaveBeenCalled();
    });

    test('ignores messages with no data payload', () => {
      const callback = jest.fn();
      SubtitleExtractor.extract(callback);

      postRawMessage(null);

      expect(callback).not.toHaveBeenCalled();
    });
  });

  describe('One-shot behavior (Phase 53.1)', () => {
    test('removes the listener after the first caption message (does not fire twice)', () => {
      const callback = jest.fn();
      SubtitleExtractor.extract(callback);

      postCaptionMessage({ parsedEntries: [{ startMs: 0, endMs: 1, text: 'a' }] });
      postCaptionMessage({ parsedEntries: [{ startMs: 0, endMs: 1, text: 'b' }] });

      expect(callback).toHaveBeenCalledTimes(1);
    });

    test('extract() destroys any prior listener before installing a new one', () => {
      const firstCallback = jest.fn();
      SubtitleExtractor.extract(firstCallback);

      // Second extract() call should tear down the first listener.
      const secondCallback = jest.fn();
      SubtitleExtractor.extract(secondCallback);

      postCaptionMessage({ parsedEntries: [{ startMs: 0, endMs: 1, text: 'x' }] });

      expect(firstCallback).not.toHaveBeenCalled();
      expect(secondCallback).toHaveBeenCalledTimes(1);
    });

    test('extract() can be called without a callback (no throw on message)', () => {
      expect(() => SubtitleExtractor.extract()).not.toThrow();
      expect(() => postCaptionMessage({ parsedEntries: [] })).not.toThrow();
    });
  });

  describe('source language derivation (deriveSourceLang)', () => {
    test('single track with a known languageCode → that code', () => {
      expect(deriveSourceLang([{ languageCode: 'ja', languageName: 'Japanese' }])).toBe('ja');
    });

    test('multiple tracks → auto (ambiguous which the panel rendered)', () => {
      expect(deriveSourceLang([{ languageCode: 'en' }, { languageCode: 'ja' }])).toBe('auto');
    });

    test('single track with an empty languageCode → auto', () => {
      expect(deriveSourceLang([{ languageCode: '', languageName: 'Unknown' }])).toBe('auto');
    });

    test('null / empty tracks → auto', () => {
      expect(deriveSourceLang(null)).toBe('auto');
      expect(deriveSourceLang([])).toBe('auto');
      expect(deriveSourceLang(undefined)).toBe('auto');
    });

    test('routes the derived language through to the callback as the 4th argument', () => {
      const callback = jest.fn();
      SubtitleExtractor.extract(callback);

      const tracks = [{ languageCode: 'ja', languageName: 'Japanese', isAutoGenerated: true }];
      const parsedEntries = [{ startMs: 0, endMs: 1000, text: 'こんにちは' }];
      postCaptionMessage({ tracks, parsedEntries });

      expect(callback).toHaveBeenCalledWith(tracks, parsedEntries, null, 'ja');
    });
  });

  describe('destroy()', () => {
    test('removes the listener so later messages do not fire the callback', () => {
      const callback = jest.fn();
      SubtitleExtractor.extract(callback);

      SubtitleExtractor.destroy();
      postCaptionMessage({ parsedEntries: [{ startMs: 0, endMs: 1, text: 'q' }] });

      expect(callback).not.toHaveBeenCalled();
    });

    test('is safe to call when no listener is registered', () => {
      expect(() => SubtitleExtractor.destroy()).not.toThrow();
    });
  });
});
