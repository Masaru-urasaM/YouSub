(function () {
  'use strict';
  var YS = window.YouSub || (window.YouSub = {});

  // ---------------------------------------------------------------------------
  // Translation helper
  // ---------------------------------------------------------------------------

  /**
   * Send subtitle texts to background worker for translation.
   */
  function requestTranslation(parsedEntries, videoId, sourceLang, providedTargetLang) {
    return new Promise(function (resolve) {
      var texts = parsedEntries.map(function (e) { return e.text; });
      var targetLang = providedTargetLang || (YS.Constants ? YS.Constants.DEFAULT_TARGET_LANG : 'vi');
 
      console.log('[YouSub] Main: Sending', texts.length, 'entries for translation →', targetLang);
 
      browser.runtime.sendMessage(
        {
          type: 'YOUSUB_TRANSLATE_REQUEST',
          videoId: videoId,
          texts: texts,
          sourceLang: sourceLang || 'auto',
          targetLang: targetLang
        },
        function (response) {
          if (browser.runtime.lastError) {
            console.error('[YouSub] Main: Translation message error:', browser.runtime.lastError.message);
            resolve(parsedEntries);
            return;
          }

          if (response && response.success && Array.isArray(response.translated)) {
            var hadFallback = !!response.hadFallback;

            var translated = parsedEntries.map(function (entry, i) {
              return {
                startMs: entry.startMs,
                endMs: entry.endMs,
                original: entry.text,
                text: response.translated[i] || entry.text
              };
            });

            if (hadFallback) {
              console.warn('[YouSub] Main: Translation had fallback batches (some lines are original text). Check API settings.');
            } else {
              console.log('[YouSub] Main: Translation complete!');
            }

            resolve(translated);
          } else {
            console.warn('[YouSub] Main: Translation failed:', response && response.error);
            resolve(parsedEntries);
          }
        }
      );
    });
  }
 
  // ---------------------------------------------------------------------------
  // Main flow
  // ---------------------------------------------------------------------------
 
  /**
   * Helper: Select best caption track from metadata.
   */
  function selectBestTrack(tracks) {
    if (!tracks || tracks.length === 0) return null;
 
    // Priorities: 
    // 1. Vietnamese (vi) Manual
    // 2. Vietnamese (vi) Auto
    // 3. English (en) Manual
    // 4. Any Manual
    // 5. Any Auto
    var viManual = tracks.find(function (t) { return t.languageCode === 'vi' && !t.isAutoGenerated; });
    if (viManual) return viManual;
 
    var viAuto = tracks.find(function (t) { return t.languageCode === 'vi' && t.isAutoGenerated; });
    if (viAuto) return viAuto;
 
    var enManual = tracks.find(function (t) { return t.languageCode === 'en' && !t.isAutoGenerated; });
    if (enManual) return enManual;
 
    var anyManual = tracks.find(function (t) { return !t.isAutoGenerated; });
    if (anyManual) return anyManual;
 
    return tracks[0];
  }
 
  /**
   * Process extracted/parsed entries: translate and sync.
   */
  async function processEntries(entries, videoId) {
    if (!entries || entries.length === 0) return;
    
    if (YS.Overlay) YS.Overlay.showStatus('Translating...', 'info', 2000);
    
    // requestTranslation returns a Promise
    var translatedEntries = await requestTranslation(entries, videoId, 'auto');
    
    if (translatedEntries && translatedEntries.length > 0) {
      if (YS.Overlay) YS.Overlay.showStatus('Translation ready!', 'success', 2000);
      YS._lastSubtitles = translatedEntries;
    } else {
      if (YS.Overlay) YS.Overlay.showStatus('Translation failed - showing original', 'warning', 4000);
      YS._lastSubtitles = entries;
    }
 
    // Ensure elements are bound and sync is running
    YS.VideoBinder.bind(function (video) {
      if (YS.SyncEngine) YS.SyncEngine.start(YS._lastSubtitles, video);
    });
  }
 
  /**
   * Main entry point for the subtitle processing pipeline.
   * Uses a Hybrid approach: Try XHR Fetch first, fallback to DOM Scraping.
   */
  async function startSubtitlePipeline(videoId) {
    console.log('[YouSub] Starting pipeline for video:', videoId);
    
    if (YS.Overlay) YS.Overlay.showStatus('Extracting subtitles...', 'info', 2000);
 
    // Step 1: Discover tracks and check live status via a quick extraction probe
    YS.SubtitleExtractor.extract(async function (tracks, parsedEntries, error) {
      // 1.1 Handle Livestream
      if (error === 'LIVE_STREAM_DETECTED') {
        if (YS.Overlay) YS.Overlay.showStatus('Livestreams are not yet supported', 'warning', 5000);
        return;
      }
 
      // 1.2 If we already got parsed entries (DOM scraping worked or was cached)
      if (parsedEntries && parsedEntries.length > 0) {
        processEntries(parsedEntries, videoId);
        return;
      }
 
      // 1.3 If we have tracks but no entries, try Hybrid Fetch (XHR)
      if (tracks && tracks.length > 0) {
        var bestTrack = selectBestTrack(tracks);
        if (bestTrack && bestTrack.baseUrl && YS.SubtitleParser) {
          console.log('[YouSub] Hybrid: Attempting XHR fetch for track:', bestTrack.languageCode);
          try {
            var fetchedEntries = await YS.SubtitleParser.fetch(bestTrack.baseUrl);
            if (fetchedEntries && fetchedEntries.length > 0) {
              console.log('[YouSub] Hybrid: XHR fetch success!');
              processEntries(fetchedEntries, videoId);
              return;
            }
          } catch (e) {
            console.warn('[YouSub] Hybrid: XHR fetch failed, falling back to DOM scraping logic.', e);
          }
        }
      }
      
      // 1.4 If we reach here, it means neither XHR nor the initial DOM scraping result worked yet.
      if (!parsedEntries && error) {
        if (YS.Overlay) YS.Overlay.showStatus('Extraction failed: ' + error, 'error', 5000);
      } else if (!parsedEntries && !tracks) {
        if (YS.Overlay) YS.Overlay.showStatus('Could not find subtitles for this video', 'warning', 4000);
      }
    });
  }
 
  // Use the PageDetector to handle enter/leave
  YS.PageDetector.init(
    function onEnter(videoId) {
      console.log('[YouSub] Main: Video page entered. Video ID: ' + videoId);
      // Wait for binding
      YS.VideoBinder.bind(function(videoEl) {
        console.log('[YouSub] Main: Video element bound. Ready.');
      });
    }, 
    function onLeave() {
      console.log('[YouSub] Main: Video page left — cleanup.');
      if (YS.SyncEngine) YS.SyncEngine.stop();
      YS._lastSubtitles = null;
      YS.VideoBinder.unbind();
      if (YS.Overlay) YS.Overlay.destroy();
      if (YS.SubtitleExtractor) YS.SubtitleExtractor.destroy();
    }
  );
 
  // Listen for popup trigger
  browser.runtime.onMessage.addListener(function(message, sender, sendResponse) {
    if (message.type === 'YOUSUB_START_EXTRACTION') {
      sendResponse({ started: true });
      var videoId = YS.PageDetector.getCurrentVideoId();
      if (videoId) {
        startSubtitlePipeline(videoId);
      }
    } else if (message.type === 'YOUSUB_TOGGLE_DUAL_MODE') {
      if (YS.SyncEngine) {
        YS.SyncEngine.setDualMode(!!message.enabled);
      }
    } else if (message.type === 'YOUSUB_DEBUG_LOG') {
      const { msg, color, bold } = message;
      const style = `color: ${color || '#fff'}; ${bold ? 'font-weight: bold;' : ''}`;
      console.log(`%c[YouSub-Bg] ${msg}`, style);
    }
  });

  console.log('[YouSub] Content Script main module loaded.');
})();
