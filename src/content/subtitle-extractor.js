import { devLog, devWarn } from '../shared/constants.js';

let messageHandler = null;

/**
 * Inject a script file into the MAIN world to bypass CSP 'unsafe-inline'.
 */
function injectScriptFile(file) {
  devLog('[YouSub] SubtitleExtractor: Injecting script file:', file);
  try {
    const script = document.createElement('script');
    script.src = chrome.runtime.getURL(file);
    script.onload = function () {
      devLog('[YouSub] SubtitleExtractor: Script loaded and removed from DOM:', file);
      this.remove();
    };
    script.onerror = function (e) {
      console.error('[YouSub] SubtitleExtractor: Script injection FAILED:', file, e);
    };
    (document.head || document.documentElement).appendChild(script);
  } catch (err) {
    console.error('[YouSub] SubtitleExtractor: Critical injection error:', err);
  }
}

/**
 * Best-effort source language of the DOM-scraped transcript.
 *
 * We only assert a concrete language when it is UNAMBIGUOUS — exactly one caption
 * track carrying a known languageCode — because a WRONG source language would make
 * the downstream on-device rough back-translation (MergeFixer verification) produce
 * garbage rather than degrade cleanly. With zero or multiple tracks we cannot tell
 * which track the transcript panel rendered, so we return 'auto', which safely
 * disables on-device rough translation in the background. See
 * YOUSUB_DESIGN_DECISIONS.md (Decision 16).
 *
 * @param {Array|null} tracks — [{languageCode, ...}] caption tracks metadata.
 * @returns {string} A concrete language code, or 'auto' when undeterminable.
 */
export function deriveSourceLang(tracks) {
  if (Array.isArray(tracks) && tracks.length === 1 && tracks[0] && tracks[0].languageCode) {
    return tracks[0].languageCode;
  }
  return 'auto';
}

export const SubtitleExtractor = {
  /**
   * Extract subtitle data from YouTube.
   * Primary: Transcript DOM scraping (bypasses pot/token issues).
   *
   * @param {function(Array|null, Array|null, string|null, string)} callback
   *   Called with (tracks, parsedEntries, error, sourceLang).
   *   - tracks: [{languageCode, languageName, isAutoGenerated}]
   *   - parsedEntries: [{startMs, endMs, text}] — ready-to-use subtitle data
   *   - error: string or null
   *   - sourceLang: best-effort source language code, or 'auto' when undeterminable
   *     (see deriveSourceLang)
   */
  extract: function (callback) {
    this.destroy();

    messageHandler = function (event) {
      if (event.source !== window) return;
      if (!event.data || event.data.type !== 'YOUSUB_CAPTION_TRACKS') return;

      const tracks = event.data.tracks;
      const parsedEntries = event.data.parsedEntries;
      const error = event.data.error;

      if (error) {
        devWarn('[YouSub] SubtitleExtractor: Error —', error);
      }

      if (parsedEntries && parsedEntries.length > 0) {
        devLog(
          '[YouSub] SubtitleExtractor: Received',
          parsedEntries.length,
          'parsed entries from transcript DOM.'
        );
      } else if (tracks && tracks.length > 0) {
        devLog(
          '[YouSub] SubtitleExtractor: Found',
          tracks.length,
          'track(s) but no parsed entries.'
        );
        tracks.forEach(function (t, i) {
          devLog(
            '  [' + i + ']',
            t.languageCode,
            '(' + t.languageName + ')',
            t.isAutoGenerated ? '[Auto-generated]' : '[Manual]'
          );
        });
      } else {
        devLog('[YouSub] SubtitleExtractor: No subtitle data available.');
      }

      // Phase 53.1: One-shot — remove listener after callback fires
      this.destroy();

      if (callback) {
        callback(tracks, parsedEntries, error, deriveSourceLang(tracks));
      }
    }.bind(this);

    window.addEventListener('message', messageHandler);
    injectScriptFile('src/content/main-world-extractor.js');
    devLog('[YouSub] SubtitleExtractor: Injected extraction script.');
  },

  /**
   * Clean up the message listener.
   */
  destroy: function () {
    if (messageHandler) {
      window.removeEventListener('message', messageHandler);
      messageHandler = null;
    }
  },
};

// Compatibility for legacy global access
if (typeof window !== 'undefined') {
  window.YouSub = window.YouSub || {};
  window.YouSub.SubtitleExtractor = SubtitleExtractor;
}
