(function () {
  'use strict';
  var YouSub = window.YouSub || (window.YouSub = {});

  var messageHandler = null;

  /**
   * Inject a script file into the MAIN world to bypass CSP 'unsafe-inline'.
   */
  function injectScriptFile(file) {
    var script = document.createElement('script');
    script.src = chrome.runtime.getURL(file);
    script.onload = function () { this.remove(); };
    (document.head || document.documentElement).appendChild(script);
  }

  YouSub.SubtitleExtractor = {
    /**
     * Extract subtitle data from YouTube.
     * Primary: Transcript DOM scraping (bypasses pot/token issues).
     *
     * @param {function(Array|null, Array|null, string|null)} callback
     *   Called with (tracks, parsedEntries, error).
     *   - tracks: [{languageCode, languageName, isAutoGenerated}]
     *   - parsedEntries: [{startMs, endMs, text}] — ready-to-use subtitle data
     *   - error: string or null
     */
    extract: function (callback) {
      this.destroy();

      messageHandler = function (event) {
        if (event.source !== window) return;
        if (!event.data || event.data.type !== 'YOUSUB_CAPTION_TRACKS') return;

        var tracks = event.data.tracks;
        var parsedEntries = event.data.parsedEntries;
        var error = event.data.error;

        if (error) {
          console.warn('[YouSub] SubtitleExtractor: Error —', error);
        }

        if (parsedEntries && parsedEntries.length > 0) {
          console.log('[YouSub] SubtitleExtractor: Received', parsedEntries.length, 'parsed entries from transcript DOM.');
        } else if (tracks && tracks.length > 0) {
          console.log('[YouSub] SubtitleExtractor: Found', tracks.length, 'track(s) but no parsed entries.');
          tracks.forEach(function (t, i) {
            console.log(
              '  [' + i + ']',
              t.languageCode,
              '(' + t.languageName + ')',
              t.isAutoGenerated ? '[Auto-generated]' : '[Manual]'
            );
          });
        } else {
          console.log('[YouSub] SubtitleExtractor: No subtitle data available.');
        }

        if (callback) {
          callback(tracks, parsedEntries, error);
        }
      };

      window.addEventListener('message', messageHandler);
      injectScriptFile('src/content/main-world-extractor.js');
      console.log('[YouSub] SubtitleExtractor: Injected extraction script.');
    },

    /**
     * Clean up the message listener.
     */
    destroy: function () {
      if (messageHandler) {
        window.removeEventListener('message', messageHandler);
        messageHandler = null;
      }
    }
  };
})();
